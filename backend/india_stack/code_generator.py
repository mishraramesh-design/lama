def generate_for_project(selected: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Generate all files for the supplied list of selections.

    selected = [{component_id, attach_to (service_name|'new'), mode, sandbox_provider, env}, …]
    """
    files: List[Dict[str, Any]] = []
    if not selected:
        return files

    # Common infra (only emitted when at least one component is selected).
    files.append({
        "path": "backend/india_stack_common.py",
        "content": INDIA_STACK_MIDDLEWARE,
        "kind": "infra",
        "service_name": "india-stack",
    })
    files.append({
        "path": "backend/india_stack_mocks.py",
        "content": _mock_module(),
        "kind": "infra",
        "service_name": "india-stack",
    })
    files.append({
        "path": "backend/india_stack_config.env",
        "content": _env_block(selected),
        "kind": "config",
        "service_name": "india-stack",
    })
    files.append({
        "path": "backend/tests/test_india_stack_compliance.py",
        "content": _compliance_tests(selected),
        "kind": "test",
        "service_name": "india-stack",
    })

    for sel in selected:
        cat = by_id(sel["component_id"])
        if not cat:
            continue
        target_service = sel.get("attach_to") or "india-stack"

        # Backend router
        files.append({
            "path": f"backend/india/{cat['id']}_router.py",
            "content": _backend_router(
                cat["id"], cat["name"], cat["endpoints"],
                f"{cat['id'].upper()}_PROVIDER", cat.get("consent_kind"),
            ),
            "kind": "backend",
            "service_name": target_service,
        })
        # Frontend widget
        path, content = _frontend_component(cat["id"], cat["name"])
        files.append({
            "path": path, "content": content,
            "kind": "frontend", "service_name": target_service,
        })

    # Aggregator that mounts every router on the FastAPI app.
    mount = ["from fastapi import FastAPI", ""]
    for sel in selected:
        cat = by_id(sel["component_id"])
        if not cat:
            continue
        mount.append(f"from india.{cat['id']}_router import router as {cat['id']}_router")
    mount.append("")
    mount.append("def mount_india_stack(app: FastAPI) -> None:")
    if not selected:
        mount.append("    return")
    else:
        for sel in selected:
            cat = by_id(sel["component_id"])
            if not cat:
                continue
            mount.append(f"    app.include_router({cat['id']}_router)")
    files.append({
        "path": "backend/india_stack_mount.py",
        "content": "\n".join(mount) + "\n",
        "kind": "infra",
        "service_name": "india-stack",
    })
    return files
