def _env_block(selected: list[dict]) -> str:
    lines = [
        "# India-Stack configuration generated by LAMA.",
        "# Default mode is `mock` — set <COMPONENT>_PROVIDER to a real value to switch to sandbox.",
        "",
    ]
    for sel in selected:
        cat = by_id(sel["component_id"])
        if not cat:
            continue
        lines.append(f"# ── {cat['name']} ──")
        for var, hint in cat["env_vars"]:
            current = sel.get("env", {}).get(var, "")
            lines.append(f"{var}={current}    # {hint}")
        lines.append("")
    return "\n".join(lines)


