# ─── Circuit-breaker ────────────────────────────────────────────────────────
class CircuitBreaker:
    """Per-component CB. Opens after `threshold` consecutive failures, half-open after `reset_sec`."""

    def __init__(self, name: str, threshold: int = 5, reset_sec: int = 30):
        self.name = name
        self.threshold = threshold
        self.reset_sec = reset_sec
        self.failures = 0
        self.opened_at: float = 0.0

    def allow(self) -> bool:
        if self.failures < self.threshold:
            return True
        if time.time() - self.opened_at > self.reset_sec:
            self.failures = 0  # half-open
            return True
        return False

    def record(self, success: bool):
        if success:
            self.failures = 0
        else:
            self.failures += 1
            if self.failures >= self.threshold:
                self.opened_at = time.time()


BREAKERS: dict[str, CircuitBreaker] = {}


def breaker(name: str) -> CircuitBreaker:
    if name not in BREAKERS:
        BREAKERS[name] = CircuitBreaker(name)
    return BREAKERS[name]


